// Builds a static copy of the site for Hostinger (Apache + PHP) into ./out.
//   npm run build:hostinger
// Then the contents of ./out are pushed to the `hostinger` branch, which Hostinger
// deploys into public_html (hPanel → Advanced → GIT).
import { execSync } from "node:child_process";
import { cpSync, existsSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";

const API = "src/app/api";
const PARKED = ".hostinger-api-parked";
const SITE = "www.scalewithads.us";

// Route handlers can't be statically exported; hostinger/api/lead.php replaces /api/lead.
if (existsSync(API)) renameSync(API, PARKED);
try {
  rmSync("out", { recursive: true, force: true });
  execSync("npx next build", { stdio: "inherit", env: { ...process.env, HOSTINGER_EXPORT: "1" } });
} finally {
  if (existsSync(PARKED)) renameSync(PARKED, API);
}

cpSync("hostinger/api", "out/api", { recursive: true });

const esc = (p) => p.replace(/^\//, "").replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const redirects = JSON.parse(readFileSync("redirects.json", "utf8"))
  .map((r) => `RewriteRule ^${esc(r.source)}/?$ ${r.destination} [R=301,L]`)
  .join("\n");

writeFileSync(
  "out/.htaccess",
  `# Generated by scripts/build-hostinger.mjs. Do not edit on the server.
Options -MultiViews -Indexes
DirectorySlash Off
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
RewriteEngine On

# Always https://${SITE}
RewriteCond %{HTTPS} off [OR]
RewriteCond %{HTTP_HOST} !^${esc(SITE)}$ [NC]
RewriteRule ^ https://${SITE}%{REQUEST_URI} [R=301,L]

# Permanent redirects (same list as Vercel, from redirects.json)
${redirects}

# Lead form endpoint
RewriteRule ^api/lead/?$ api/lead.php [L]

# Remove trailing slashes: /services/ -> /services
RewriteCond %{REQUEST_URI} !^/$
RewriteRule ^(.+)/$ /$1 [R=301,L]

# Clean URLs: /services -> services.html
RewriteCond %{REQUEST_FILENAME}.html -f
RewriteRule ^(.+)$ $1.html [L]
</IfModule>

<IfModule mod_headers.c>
  <FilesMatch "\\.html$">
    Header set Cache-Control "no-cache, must-revalidate"
  </FilesMatch>
</IfModule>
<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType text/css "access plus 1 year"
  ExpiresByType application/javascript "access plus 1 year"
  ExpiresByType image/webp "access plus 1 month"
  ExpiresByType image/png "access plus 1 month"
  ExpiresByType image/jpeg "access plus 1 month"
  ExpiresByType video/mp4 "access plus 1 month"
</IfModule>
`,
);

// Server-only files that must never be overwritten by a deploy.
writeFileSync("out/.gitignore", "api/config.php\napi/leads.log\n");
console.log("\nHostinger build ready in ./out");
